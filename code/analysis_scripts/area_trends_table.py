#!/usr/bin/env python
"""Supplement table of the climate at the six areas of the pre-2000 comparison.
Reads tables/area_climate_trends.csv (scripts/area_climate_trends.py); writes tables/S15_area_climate_trends.tex.
Usage: python scripts/area_trends_table.py"""
from pathlib import Path
import pandas as pd
ROOT = Path(__file__).resolve().parents[1]
T = pd.read_csv(ROOT / "tables" / "area_climate_trends.csv")
FORC = ["ERA5", "ERA5-Land", "HARv2", "CRU_TS4", "CHELSA"]
HEAD = "ERA5 & ERA5-Land & HARv2 & CRU~TS4 & CHELSA"
AREAS = list(dict.fromkeys(T.area))
NAME = {a: a.replace("Himalaya 650 largest (Maurer)", "Himalaya (650 largest)").replace("Karakoram (Zhou)", "Karakoram")
        .replace("W Nyainqentanglha", "W.\\ Nyainqentanglha") for a in AREAS}
sg = lambda v, nd: ("$+$" if v >= 0 else "$-$") + f"{abs(v):.{nd}f}"
PANELS = [("(a) Temperature trend ($^\\circ$C per decade)", "T_trend_per_decade", lambda v: sg(v, 2)),
          ("(b) Mean precipitation (mm\\,yr$^{-1}$)", "P_mean_mm", lambda v: f"{v:,.0f}".replace(",", "\\,")),
          ("(c) Precipitation trend (\\% per decade)", "P_trend_pct_per_decade", lambda v: sg(v, 1))]
L = ["% generated by scripts/area_trends_table.py -- do not edit by hand", "\\begin{table}[t]",
     "\\caption{Climate of the five products at the six areas of the pre-2000 comparison, 1975--1999 (HARv2 1980--1999, "
     "CHELSA-W5E5 1979--1999), area-weighted over the glaciers of each sample. Temperature is at the median glacier elevation; "
     "precipitation is the value of the product.}",
     "\\label{tab:area_trends}", "\\scriptsize", "\\begin{tabular}{lrrrrr}", "\\tophline"]
for i, (title, col, f) in enumerate(PANELS):
    if i: L.append("\\middlehline")
    L += [f"{title} & {HEAD} \\\\", "\\middlehline"]
    P = T.pivot(index="area", columns="forcing", values=col)
    for a in AREAS:
        L.append(f"{NAME[a]} & " + " & ".join(f(P.loc[a, c]) for c in FORC) + " \\\\")
L += ["\\bottomhline", "\\end{tabular}", "\\end{table}"]
(ROOT / "tables" / "S15_area_climate_trends.tex").write_text("\n".join(L) + "\n")
print("wrote tables/S15_area_climate_trends.tex")
