#!/usr/bin/env python
"""Climate trends and steps of the five forcings at the median glacier elevation (glacier-area-weighted, HMA), from
tables/climate_series_<F>.csv (scripts/climate_series.py), against the 1980-1999 reconstruction (tables/T3_volume_windows.csv).
  T_zmed / P trend per decade (OLS) for 2000-2019 and 1980-2019 (CHELSA-W5E5: years available, to 2016);
  step = mean over the calibration period (2000-2019; CHELSA-W5E5 2000-2009) minus mean 1980-1999, for T_zmed and P (%).
Also prints the 1980-1999 HMA best estimate without CHELSA-W5E5 (equal family weights, period means of analysis/B_regional_series.csv).
Outputs: tables/climate_trends.csv, tables/S16_climate_trends.tex."""
from pathlib import Path
import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
FORC = ["ERA5", "ERA5-Land", "HARv2", "CRU_TS4", "CHELSA"]
LAB = {"ERA5": "ERA5", "ERA5-Land": "ERA5-Land", "HARv2": "HARv2", "CRU_TS4": "CRU~TS4", "CHELSA": "CHELSA-W5E5"}
CAL = {f: (2000, 2019) for f in FORC}; CAL["CHELSA"] = (2000, 2009)
rows, wide = [], []
v = pd.read_csv(ROOT / "tables/T3_volume_windows.csv")
v = v[v.window == "recon_1980-1999"].set_index("forcing").dV_pct_V1999
for f in FORC:
    c = pd.read_csv(ROOT / f"tables/climate_series_{f}.csv").set_index("year")
    w = dict(forcing=f)
    for a, b in [(2000, 2019), (1980, 2019)]:
        r = dict(forcing=f, period=f"{a}-{b}")
        for col in ["T_zmed", "P"]:
            s = c[col].loc[a:b].dropna()
            r[f"{col}_trend_per_decade"] = np.polyfit(s.index, s.values, 1)[0] * 10 if len(s) >= 10 else np.nan
            r[f"{col}_n_years"] = len(s)
            w[f"{col}_trend_{a}_{b}"] = r[f"{col}_trend_per_decade"]
        rows.append(r)
    a, b = CAL[f]
    w["T_step"] = c.T_zmed.loc[a:b].mean() - c.T_zmed.loc[1980:1999].mean()
    w["P_step_pct"] = 100 * (c.P.loc[a:b].mean() / c.P.loc[1980:1999].mean() - 1)
    w["dV_1980_1999_pct_V1999"] = v[f]
    wide.append(w)
T = pd.DataFrame(rows); T.to_csv(ROOT / "tables/climate_trends.csv", index=False)
W = pd.DataFrame(wide).set_index("forcing")
W.to_csv(ROOT / "tables/climate_steps.csv")
print(T.round(3).to_string(index=False)); print(W.round(3).to_string())
print("Spearman rho(T_step, dV 1980-1999):", round(W.T_step.rank().corr(W.dV_1980_1999_pct_V1999.rank()), 2))
B = pd.read_csv(ROOT / "analysis/B_regional_series.csv")
m = B[(B.level == "hma") & B.year.between(1980, 1999)].groupby("forcing").B_mwe.mean()
e = m[["ERA5", "ERA5-Land", "HARv2"]].mean()
print(f"1980-1999 equal family: with CHELSA {(e + m[['CRU_TS4', 'CHELSA']].mean()) / 2:+.3f}, without {(e + m['CRU_TS4']) / 2:+.3f}")
f2 = lambda x, nd=2: "--" if pd.isna(x) else (("$+$" if x > 0 else "$-$") + f"{abs(x):.{nd}f}" if abs(x) >= 0.5 * 10 ** -nd else f"{0:.{nd}f}")
L = ["% generated by scripts/climate_trends.py -- do not edit by hand", "\\begin{table}[t]",
     "\\caption{Temperature and precipitation of the five forcings at the median glacier elevation (glacier-area-weighted over HMA, as in Fig.~\\ref{fig:climate} of the main text): linear trend of annual temperature ($^\\circ$C per decade) and precipitation (mm\\,yr$^{-1}$ per decade), and the step from 1980--1999 to the calibration period (2000--2019; CHELSA-W5E5 2000--2009) in temperature ($^\\circ$C) and precipitation (\\%), next to the reconstructed 1980--1999 volume change (\\% of $V_{1999}$). CHELSA-W5E5 ends in 2016; its trends use the years available.}",
     "\\label{tab:climtrends}", "\\scriptsize", "\\begin{tabular}{lrrrrrrr}", "\\tophline",
     " & \\multicolumn{2}{c}{$T$ trend} & \\multicolumn{2}{c}{$P$ trend} & \\multicolumn{2}{c}{Step to calibration period} & $\\Delta V$ \\\\",
     "Forcing & 2000--2019 & 1980--2019 & 2000--2019 & 1980--2019 & $\\Delta T$ & $\\Delta P$ (\\%) & 1980--1999 \\\\", "\\middlehline"]
for f, r in W.iterrows():
    L.append(f"{LAB[f]} & {f2(r.T_zmed_trend_2000_2019)} & {f2(r.T_zmed_trend_1980_2019)} & {f2(r.P_trend_2000_2019, 1)} & {f2(r.P_trend_1980_2019, 1)} & "
             f"{f2(r.T_step)} & {f2(r.P_step_pct, 1)} & {f2(r.dV_1980_1999_pct_V1999)} \\\\")
L += ["\\bottomhline", "\\end{tabular}", "\\end{table}"]
(ROOT / "tables/S16_climate_trends.tex").write_text("\n".join(L) + "\n")
