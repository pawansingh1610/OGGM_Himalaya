#!/usr/bin/env python
"""Compact LaTeX versions of Table 3 (HMA volume windows) and Table 7 (basins), rewritten after the
author's comments on Draft_2 (p. 12: "very confusing table, spread more evenly"; p. 26: "simplify, use the
plot and a simplified table").

Reads only CSVs in tables/ (written by make_figures.py and population_basins.py), so it can be re-run at any
time:  python scripts/tables_tex.py
Outputs: tables/T3_volume_windows.tex, tables/T6_basin_glacier_population.tex,
tables/S10_area_residual.tex (from tables/area_consistency_residual_run06.csv, scripts/area_residual_run06.py)
(the full basin table with all windows and epochs stays as Table S9: tables/S9_basin_detail.tex,
written by population_basins.py)
"""
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
TAB = ROOT / "tables"
FORC = ["ERA5", "ERA5-Land", "HARv2", "CRU_TS4", "CHELSA"]
LABEL = {"ERA5": "ERA5", "ERA5-Land": "ERA5-Land", "HARv2": "HARv2", "CRU_TS4": "CRU~TS4", "CHELSA": "CHELSA-W5E5"}


def num(x, nd=0, sign=True):
    if x is None or pd.isna(x):
        return "--"
    s = f"{x:+,.{nd}f}" if sign else f"{x:,.{nd}f}"
    return s.replace(",", "\\,").replace("-", "$-$")


def mpop(x):
    return "$<$0.1" if x < 0.05 else num(x, 1, False)


def write(name, lines):
    p = TAB / f"{name}.tex"
    p.write_text("% generated by scripts/tables_tex.py -- do not edit by hand\n" + "\n".join(lines) + "\n")
    print(f"  -> {p.relative_to(ROOT)}")


# ------------------------------------------------------------------ Table 3: HMA volume windows
def t3():
    d = pd.read_csv(TAB / "T3_volume_windows.csv")
    groups = [("Reconstruction and calibration period", [("recon_1980-1999", "1980--1999"),
                                                        ("fwd_2000-2016", "2000--2016"),
                                                        ("fwd_2000-2019", "2000--2019$^a$"),
                                                        ("full_1980-2016", "1980--2016")]),
              ("Including the extrapolation", [("fwd_2000-2025", "2000--2025$^b$")]),
              ("Before 1980: not constrained$^c$", [("recon_1950-1979", "1950--1979"),
                                                   ("recon_1950-1999", "1950--1999"),
                                                   ("full_1950-2019", "1950--2019"),
                                                   ("full_1950-2025", "1950--2025$^b$")])]
    v99 = d.groupby("forcing").V_1999_km3.first().reindex(FORC)
    ncol = len(FORC) + 2
    L = ["\\begin{table*}[t]",
         "\\caption{HMA ice-volume change per window and forcing; negative = loss. (a) In km$^3$ of ice "
         "(1\\,km$^3$ ice = 0.9\\,Gt). (b) In per cent of $V_{1999}$, the consensus volume at the end of 1999 of the same "
         "glacier sample (" + ", ".join(f"{LABEL[f]} {v:,.0f}".replace(",", "\\,") for f, v in v99.items())
         + "\\,km$^3$). Window: $V$(end of the last year) $-$ $V$(end of the year before the first). "
         "Spread: maximum minus minimum across forcings. -- : forcing does not cover the window. "
         "$^a$ Matched to the geodetic target by construction. $^b$ 2020--2025 is an unconstrained extrapolation. "
         "$^c$ The forcings disagree in sign; shown for completeness only.}",
         "\\label{tab:volume}",
         "\\small",
         "\\renewcommand{\\arraystretch}{1.12}",
         "\\begin{tabular*}{\\textwidth}{@{\\extracolsep{\\fill}}l" + "r" * (ncol - 1) + "}",
         "\\tophline",
         "Window & " + " & ".join(LABEL[f] for f in FORC) + " & Spread \\\\"]
    for panel, col, nd, unit in [("(a) Volume change (km$^3$ ice)", "dV_km3", 0, "km$^3$"),
                                 ("(b) Volume change (\\% of $V_{1999}$)", "dV_pct_V1999", 2, "p.p.")]:
        L += ["\\middlehline", f"\\multicolumn{{{ncol}}}{{l}}{{\\textbf{{{panel}}}}} \\\\"]
        for gname, wins in groups:
            L.append(f"\\multicolumn{{{ncol}}}{{l}}{{\\emph{{{gname}}}}} \\\\")
            for w, lab in wins:
                r = d[d.window == w].set_index("forcing").reindex(FORC)[col]
                v = r.dropna()
                spread = num(v.max() - v.min(), nd, sign=False) if len(v) > 1 else "--"
                L.append(f"\\quad {lab} & " + " & ".join(num(x, nd) for x in r) + f" & {spread} \\\\")
    L += ["\\bottomhline", "\\end{tabular*}", "\\end{table*}"]
    write("T3_volume_windows", L)


# ------------------------------------------------------------------ Table 7: basins (simplified)
def t6():
    T = pd.read_csv(TAB / "T6_basin_glacier_population.csv", index_col=0)
    T = T[T.glacier_area_km2 > 0].sort_values("V1999_consensus_km3", ascending=False)

    def rng(r, kind, nd):
        lo, hi = r[f"dV2000-2019_{kind}_min"], r[f"dV2000-2019_{kind}_max"]
        if pd.isna(lo):
            return "--"
        if kind == "km3" and max(abs(lo), abs(hi)) < 5:
            nd = 1   # small basins: one decimal instead of "-0"
        a, b = num(lo, nd), num(hi, nd)
        return a if a == b else f"{a} to {b}"

    L = ["\\begin{table*}[t]",
         "\\caption{Glacier-fed river basins: glaciers, modelled ice-volume change in 2000--2019 and population in 2020. "
         "Volume change: range across the four forcings that cover 2000--2019, in km$^3$ of ice and in per cent of the "
         "basin's $V_{1999}$ (negative = loss). Population (GHS-POP R2023A, millions): whole basin, and the HydroBASINS "
         "level-7 units that contain glaciers (glacierised catchments). Population is residential exposure, not "
         "glacier-water use. Level-6 and level-8 values: Table~\\ref{tab:S9}.}",
         "\\label{tab:basins}",
         "\\small",
         "\\renewcommand{\\arraystretch}{1.12}",
         "\\begin{tabular*}{\\textwidth}{@{\\extracolsep{\\fill}}lrrrrrrr}",
         "\\tophline",
         " & & Glacier & & \\multicolumn{2}{c}{$\\Delta V$ 2000--2019} & \\multicolumn{2}{c}{Population 2020 (M)} \\\\",
         "Basin & Glaciers & area (km$^2$) & $V_{1999}$ (km$^3$) & km$^3$ & \\% of $V_{1999}$ & basin & glacierised \\\\",
         "\\middlehline"]
    for name, r in T.iterrows():
        bname = name.replace('&', '\\&').replace('-', '--')   # outside the f-string (Python < 3.12)
        L.append(f"{bname} & {num(r.n_glaciers, 0, False)} & {num(r.glacier_area_km2, 0, False)} & "
                 f"{num(r.V1999_consensus_km3, 0 if r.V1999_consensus_km3 >= 10 else 1, False)} & {rng(r, 'km3', 0)} & {rng(r, 'pct', 1)} & "
                 f"{mpop(r.pop2020 / 1e6)} & {mpop(r.pop2020_glac_l7 / 1e6)} \\\\")
    s = T.sum(numeric_only=True)
    L += ["\\middlehline",
          f"All glacier-fed basins & {num(s.n_glaciers, 0, False)} & {num(s.glacier_area_km2, 0, False)} & "
          f"{num(s.V1999_consensus_km3, 0, False)} & & & {num(s.pop2020 / 1e6, 1, False)}$^a$ & {num(s.pop2020_glac_l7 / 1e6, 1, False)} \\\\",
          "\\bottomhline", "\\end{tabular*}"]
    full = pd.read_csv(TAB / "T6_basin_glacier_population.csv", index_col=0)
    dl = full.loc["GBM delta & Meghna", "pop2020"] / 1e6 if "GBM delta & Meghna" in full.index else None
    note = ("$^a$ Without the Ganges--Brahmaputra--Meghna delta and Meghna basin, which has no glaciers but is fed by both "
            f"rivers ({dl:.1f} million in 2020)." if dl is not None else "")
    if note:
        L.append(f"\\belowtable{{{note}}}")
    L.append("\\end{table*}")
    write("T6_basin_glacier_population", L)
    print(T[["n_glaciers", "glacier_area_km2", "V1999_consensus_km3", "dV2000-2019_pct_min", "dV2000-2019_pct_max"]]
          .round(1).to_string())
    print(f"   totals: glaciers {s.n_glaciers:.0f}, pop2020 basins {s.pop2020/1e6:.1f} M (+delta {dl:.1f}), glac L7 {s.pop2020_glac_l7/1e6:.1f} M")


# ------------------------------------------------------------------ Table S10: residual of the area-consistent target
def s10():
    D = pd.read_csv(TAB / "area_consistency_residual_run06.csv")
    reg = {"ALL_HMA": "HMA", "RGI60-13": "Region 13", "RGI60-14": "Region 14", "RGI60-15": "Region 15"}
    L = ["\\begin{table}[t]",
         "\\caption{Residual mass mismatch of the area-consistent calibration over the calibration period (2000--2019; "
         "CHELSA-W5E5 2000--2009), glaciers of the regional series. Target: $\\sum B_\\mathrm{Hug}\\,A_\\mathrm{RGI}$; "
         "model: modelled mass change. Residual = model/target $-$ 1 (negative: the model loses less mass). The residual is split "
         "exactly into three terms (percentage points of the target): glaciers with a capped factor; area drift of the other "
         "glaciers (modelled mean area smaller than in the first run from which the factor was taken); covariance of annual mass "
         "balance and area. A fourth term (calibration residual and extinction within the period) is below 0.005 points and not shown.}",
         "\\label{tab:S10}", "\\scriptsize",
         "\\begin{tabular}{llrrrrrr}", "\\tophline",
         "Forcing & Unit & Target (Gt\\,yr$^{-1}$) & Model (Gt\\,yr$^{-1}$) & Residual (\\%) & Capped & Area drift & Covariance \\\\",
         "\\middlehline"]
    for i, f in enumerate(FORC):
        g = D[D.forcing == f].set_index("region")
        if i:
            L.append("\\middlehline")
        for u in ["ALL_HMA", "RGI60-13", "RGI60-14", "RGI60-15"]:
            r = g.loc[u]
            L.append(f"{LABEL[f] if u == 'ALL_HMA' else ''} & {reg[u]} & {num(r.target_Gt_yr, 2)} & {num(r.model_Gt_yr, 2)} & "
                     f"{num(r.residual_pct, 2)} & {num(r.capped_pp, 2)} & {num(r.area_drift_pp, 2)} & {num(r.covariance_pp, 2)} \\\\")
    L += ["\\bottomhline", "\\end{tabular}", "\\end{table}"]
    write("S10_area_residual", L)


if __name__ == "__main__":
    t3()
    t6()
    s10()
