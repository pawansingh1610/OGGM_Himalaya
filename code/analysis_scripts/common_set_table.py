"""Supplement table of the common-glacier-set spread (tables/common_set_spread.csv -> tables/S14_common_set.tex).
Run after common_set.py. Reads only the csv."""
from pathlib import Path
import pandas as pd
ROOT = Path(__file__).resolve().parents[1]
T = pd.read_csv(ROOT / "tables" / "common_set_spread.csv")
nm = {"CRU_TS4": "CRU~TS4", "CHELSA": "CHELSA-W5E5"}
L = ["% generated by scripts/common_set_table.py -- do not edit by hand",
     "\\begin{table}[t]",
     "\\caption{Volume change on the common glacier set: the glaciers that have a value in every year of the window for every forcing covering it and that do not vanish backwards in any of them. Volume change in km$^3$ of ice and in per cent of the consensus volume $V_{1999}$ of the same set; negative = loss. $B$: area-weighted mean specific mass balance (m\\,w.e.\\,yr$^{-1}$). 2020--2025 is not part of this check.}",
     "\\label{tab:common}", "\\scriptsize", "\\begin{tabular}{llrrrrrr}", "\\tophline",
     "Window & Forcing & Glaciers & Area (km$^2$) & $V_{1999}$ (km$^3$) & $\\Delta V$ (km$^3$) & $\\Delta V$ (\\%) & $B$ \\\\", "\\middlehline"]
prev = None
for _, r in T.iterrows():
    w = r.window.replace("-", "--") if r.window != prev else ""
    first = r.window != prev
    prev = r.window
    dv = f"{r.dV_km3:+.0f}".replace("-", "$-$").replace("+", "$+$")
    pc = f"{r.dV_pct_V1999:+.2f}".replace("-", "$-$").replace("+", "$+$")
    b = f"{r.B_mwe:+.3f}".replace("-", "$-$").replace("+", "$+$")
    if first and L[-1] != "\\middlehline": L.append("\\hline")
    L.append(f"{w} & {nm.get(r.forcing, r.forcing)} & {r.n_glaciers:,} & {r.area_km2:,.0f} & {r.V1999_km3:,.0f} & {dv} & {pc} & {b} \\\\".replace(",", "\\,"))
L += ["\\bottomhline", "\\end{tabular}", "\\end{table}"]
(ROOT / "tables" / "S14_common_set.tex").write_text("\n".join(L) + "\n")
print("wrote tables/S14_common_set.tex")
